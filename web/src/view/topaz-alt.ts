// Drawn for any character outside 32 to 126, as a font's last glyph is.
const NOT_DEFINED = `
#######.
##...##.
##...##.
##...##.
##...##.
##...##.
#######.
........`;

export const TOPAZ_ALT_LO_CHAR = 32;
export const TOPAZ_ALT_HI_CHAR = 126;
const SIZE = 8;

// Each glyph's rows, in sheet order: 32 to 126, then "not defined".
export const topazAltRows = (): string[][] =>
  [
    ...Array.from(
      { length: TOPAZ_ALT_HI_CHAR - TOPAZ_ALT_LO_CHAR + 1 },
      (_, i) => {
        const char = String.fromCharCode(TOPAZ_ALT_LO_CHAR + i);
        const glyph = GLYPHS[char];
        if (glyph === undefined) {
          throw new Error(`topaz-alt has no glyph for ${JSON.stringify(char)}`);
        }
        return glyph;
      }
    ),
    NOT_DEFINED
  ].map(glyph => glyph.trim().split('\n'));

// The same shape as an exported font's metrics JSON.
export const TOPAZ_ALT_METRICS: FontMetrics = {
  baseline: 6,
  glyphs: Array.from(
    { length: TOPAZ_ALT_HI_CHAR - TOPAZ_ALT_LO_CHAR + 2 },
    (_, i): FontGlyph => ({
      code:
        i <= TOPAZ_ALT_HI_CHAR - TOPAZ_ALT_LO_CHAR
          ? TOPAZ_ALT_LO_CHAR + i
          : null,
      kern: 0,
      space: SIZE,
      width: SIZE,
      x: i * SIZE
    })
  ),
  height: SIZE,
  hiChar: TOPAZ_ALT_HI_CHAR,
  loChar: TOPAZ_ALT_LO_CHAR
};

// The font with its sheet drawn white on clear, as an exported sheet is.
export const topazAltFont = (): Font => {
  const glyphs = topazAltRows();
  const sheet = document.createElement('canvas');
  sheet.width = glyphs.length * SIZE;
  sheet.height = SIZE;
  const ctx = sheet.getContext('2d');
  if (!ctx) {
    throw new Error('Canvas 2D is not available');
  }
  ctx.fillStyle = '#ffffff';
  glyphs.forEach((rows, i) => {
    rows.forEach((row, y) => {
      [...row].forEach((pixel, x) => {
        if (pixel === '#') {
          ctx.fillRect(i * SIZE + x, y, 1, 1);
        }
      });
    });
  });
  return { metrics: TOPAZ_ALT_METRICS, sheet };
};
